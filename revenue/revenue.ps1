function Get-StreamsStatus {
    $streams = Get-Content $StreamsFile | ConvertFrom-Json
    Write-Host "═══════════════════════════════════════"
    Write-Host "  REVENUE STREAMS STATUS"
    Write-Host "═══════════════════════════════════════"
    
    $total = 0
    foreach ($key in $streams.PSObject.Properties.Name) {
        $s = $streams.$key
        $status = if ($s.status -eq "active") { "🟢" } elseif ($s.status -eq "ready") { "🟡" } else { "🔴" }
        Write-Host "$status $($s.name)"
        Write-Host "   Status: $($s.status)"
        if ($s.blocker) { Write-Host "   Blocker: $($s.blocker)" }
        Write-Host "   Daily: €$($s.daily_revenue) | Potential: €$($s.potential)"
        $total += $s.daily_revenue
    }
    
    Write-Host "═══════════════════════════════════════"
    Write-Host "  TOTAL DAILY: €$total"
    Write-Host "  TOTAL MONTHLY: €$($total * 30)"
    Write-Host "═══════════════════════════════════════"
}


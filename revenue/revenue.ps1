function Generate-TradingSignals {
    Write-Host "═══════════════════════════════════════"
    Write-Host "  TRADING SIGNALS"
    Write-Host "═══════════════════════════════════════"
    
    # Simple signal logic
    $signals = @()
    
    # BTC signal
    $btc = Invoke-RestMethod -Uri "https://api.coingecko.com/api/v3/simple/price?ids=bitcoin&vs_currencies=usd&include_24hr_change=true" -TimeoutSec 10
    if ($btc.bitcoin.usd_24h_change -lt -5) {
        $signals += "🟢 BTC OVERSOLD: $($btc.bitcoin.usd) | Change: $($btc.bitcoin.usd_24h_change)% | Consider DCA"
    }
    
    # MSTR signal
    $mstrData = & "C:\Users\quent\.openclaw\workspace\mission_control\market_data_service.js" --json 2>$null | ConvertFrom-Json
    if ($mstrData.assets.MSTR.change_24h -gt 5) {
        $signals += "🟢 MSTR BREAKOUT: +$($mstrData.assets.MSTR.change_24h)% | Momentum play"
    }
    
    Write-Host "Signals for today:"
    foreach ($signal in $signals) {
        Write-Host "  $signal"
    }
    
    if ($signals.Count -eq 0) {
        Write-Host "  ⚪ No strong signals today. Hold positions."
    }
}

function Generate-RevenueReport {
    $streams = Get-Content $StreamsFile | ConvertFrom-Json
    $total = 0
    foreach ($key in $streams.PSObject.Properties.Name) {
        $total += $streams.$key.daily_revenue
    }
    
    $report = @{
        date = Get-Date -Format "yyyy-MM-dd"
        total_daily = $total
        total_monthly = $total * 30
        streams = $streams
        actions = @(
            "Fix POD pricing (manual)",
            "Setup SendGrid for newsletter",
            "Create Telegram channel for signals",
            "Package code products for Gumroad"
        )
    } | ConvertTo-Json -Depth 5
    
    $report | Set-Content "$RevenueDir\report_$(Get-Date -Format 'yyyyMMdd').json"
    Write-Host "Report saved. Action items listed."
}

